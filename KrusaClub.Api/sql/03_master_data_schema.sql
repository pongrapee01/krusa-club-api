-- Master data tables (section 99.1 - 99.9)

create table if not exists public.system_status (
    id int primary key generated by default as identity,
    name varchar(50) unique not null,
    description text,
    created timestamptz not null default now(),
    created_by uuid,
    modified timestamptz not null default now(),
    modified_by uuid
);

create table if not exists public.titles (
    id uuid primary key default gen_random_uuid(),
    name varchar(50) not null,
    description text,
    status_id int not null default 1 references public.system_status(id),
    created timestamptz not null default now(),
    created_by uuid,
    modified timestamptz not null default now(),
    modified_by uuid
);

create table if not exists public.roles (
    id uuid primary key default gen_random_uuid(),
    code varchar(50) unique not null,
    name varchar(100) not null,
    description text,
    status_id int not null default 1 references public.system_status(id),
    created timestamptz not null default now(),
    created_by uuid,
    modified_at timestamptz not null default now(),
    modified uuid
);

create table if not exists public.semesters (
    id uuid primary key default gen_random_uuid(),
    academic_year varchar(4) not null,
    term varchar(2) not null,
    start_date date not null,
    end_date date not null,
    is_current boolean not null default false,
    status_id int not null default 1 references public.system_status(id),
    created timestamptz not null default now(),
    created_by uuid,
    modified timestamptz,
    modified_by uuid
);

create table if not exists public.classes (
    id uuid primary key default gen_random_uuid(),
    name varchar(50) not null,
    level varchar(20),
    status_id int not null default 1 references public.system_status(id),
    created timestamptz not null default now(),
    created_by uuid,
    modified timestamptz,
    modified_by uuid
);

create table if not exists public.periods (
    id int primary key generated by default as identity,
    period_number int not null,
    start_time time not null,
    end_time time not null,
    period_type varchar(20) not null default 'CLASS',
    status_id int not null default 1 references public.system_status(id),
    created timestamptz not null default now(),
    created_by uuid,
    modified timestamptz,
    modified_by uuid
);

create table if not exists public.subjects (
    id uuid primary key default gen_random_uuid(),
    code varchar(20) unique not null,
    name varchar(100) not null,
    credit decimal(2, 1) not null default 1.0,
    color_hex varchar(10) not null default '#E2E8F0',
    status_id int not null default 1 references public.system_status(id),
    created timestamptz not null default now(),
    created_by uuid,
    modified timestamptz,
    modified_by uuid
);

create table if not exists public.attendance_status (
    id int primary key,
    code varchar(20) unique not null,
    name_th varchar(50) not null,
    color_hex varchar(10) not null,
    icon_name varchar(50),
    status_id int not null default 1 references public.system_status(id)
);

create table if not exists public.menus (
    id uuid primary key default gen_random_uuid(),
    code varchar(50) unique not null,
    label varchar(100) not null,
    parent_code varchar(50) references public.menus(code) on delete cascade,
    path varchar(255),
    type varchar(50),
    description text,
    status_id int not null default 1 references public.system_status(id),
    created timestamptz not null default now(),
    created_by uuid,
    modified timestamptz not null default now(),
    modified_by uuid
);
